// Client approval policy types shared between firmware and bridge.
#[allow(unused_imports)]
use alloc::{
    format,
    string::{String, ToString},
    vec,
    vec::Vec,
};

use serde::{Deserialize, Serialize};

/// Maximum connection slots per master.
pub const MAX_CONNECT_SLOTS: u8 = 16;

/// Maximum client pubkeys retained per slot. A slot's secret is a shared
/// credential, so every device that pairs with it is remembered and stays
/// auto-approved. Beyond this cap the oldest entry is dropped (FIFO). Keep
/// this modest: the persisted blob for all 16 slots must fit the NVS read
/// buffer in the firmware's `load_from_nvs`.
pub const MAX_AUTHORIZED_PUBKEYS: usize = 8;

/// Maximum identities recorded as approved per slot. Beyond it an identity
/// still works but prompts on every request; nothing is evicted. With
/// 16-hex-char tags the field adds at most 265 bytes to a slot's JSON.
pub const MAX_APPROVED_IDENTITIES: usize = 16;

/// Bytes of an x-only pubkey kept per approved identity (stored as hex).
pub const IDENTITY_TAG_BYTES: usize = 8;

/// A named connection slot for a specific master.
///
/// Each slot has its own bunker URI secret. The slot -- not the ephemeral
/// client pubkey -- is the stable identity. Every client that connects with
/// the slot secret is remembered in `authorized_pubkeys` and stays auto-approved;
/// clients are never evicted by a later pairing, so multiple devices sharing one
/// slot (e.g. signet-app on a phone plus a desktop) all sign without prompting.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ConnectSlot {
    /// Slot index (0-15).
    pub slot_index: u8,
    /// Human-readable label (e.g. "nostrudel desktop").
    pub label: String,
    /// Hex-encoded 32-byte secret (64 chars). Generated by hardware RNG.
    pub secret: String,
    /// Hex-encoded most-recently-connected client pubkey. Always also present
    /// in `authorized_pubkeys`; kept separately for display ("who's active").
    #[serde(default)]
    pub current_pubkey: Option<String>,
    /// Which NIP-46 methods are auto-approved for this slot.
    /// Empty means no policy-controlled method is auto-approved.
    #[serde(default)]
    pub allowed_methods: Vec<String>,
    /// Which event kinds are auto-approved for sign_event.
    #[serde(default)]
    pub allowed_kinds: Vec<u64>,
    /// Whether to auto-approve matching requests (true) or just OLED-notify (false).
    #[serde(default)]
    pub auto_approve: bool,
    /// True once the user has physically approved a sign_event via button press.
    #[serde(default)]
    pub signing_approved: bool,
    /// When true, methods and event kinds outside this slot's policy are denied
    /// instead of falling back to a physical button prompt. New remotely-managed
    /// v2 slots set this; legacy slots default false to preserve first-sign TOFU.
    #[serde(default)]
    pub strict_permissions: bool,
    /// Every client pubkey that has paired with this slot's secret. All are
    /// auto-approvable (subject to the slot's other gates). Capped at
    /// `MAX_AUTHORIZED_PUBKEYS`. Old NVS blobs without this field deserialise
    /// to an empty vec; `current_pubkey` still matches via [`slot_authorizes`],
    /// so an already-bound client keeps working until it next re-pairs.
    #[serde(default)]
    pub authorized_pubkeys: Vec<String>,
    /// Family-bunker C4 (2026-08-14 escalation schema §1.5): when true, an
    /// interactive (ButtonRequired) request on this slot is parked and
    /// escalated to the guardian's phone instead of running the physical
    /// button window. Default false keeps today's button behaviour.
    #[serde(default)]
    pub escalate: bool,
    /// C4 §1.2: when true, a strict auto-deny on this slot records a
    /// petition and emits a low-priority guardian notice. The deny stays
    /// enforced throughout; the petition is purely a message.
    #[serde(default)]
    pub petition_on_deny: bool,
    /// C5 §2.1: when true, device-emitted audit rumors for this slot's
    /// bound identity are additionally gift-wrapped to this slot's client
    /// pubkey (the child's own paired device), best effort.
    #[serde(default)]
    pub audit_child_wrap: bool,
    /// C4/C5 guardian copy: when true, notices addressed to this slot's bound
    /// identity are additionally gift-wrapped to its current client key.
    /// Kept distinct from `audit_child_wrap`, so a dependant's audit reader
    /// never becomes an implicit guardian-notice recipient.
    #[serde(default)]
    pub guardian_notice_wrap: bool,
    /// The identity (64-char hex pubkey) this pairing is bound to, when the
    /// operator recorded one. Consulted only by the C5 child-wrap scan this
    /// cycle: a policy-decided signing as identity X wraps to every slot of
    /// the owning master with `audit_child_wrap` and `bound_identity == X`.
    #[serde(default)]
    pub bound_identity: Option<String>,
    /// Identities the owner has physically approved this pairing to sign,
    /// encrypt or decrypt as: [`identity_tag`]s (16 lowercase hex chars each)
    /// concatenated with no separator, at most [`MAX_APPROVED_IDENTITIES`].
    /// A remote client acting as any other identity is raised to a physical
    /// prompt, or escalated. Serialised as `ids` to keep the NVS blob small;
    /// old blobs without it deserialise empty, seeded lazily: `bound_identity`
    /// counts as approved and anything else prompts once.
    #[serde(default, rename = "ids", skip_serializing_if = "String::is_empty")]
    pub approved_identities: String,
}

/// A client's approval policy for a specific master.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ClientPolicy {
    /// Hex-encoded client public key (64 chars).
    pub client_pubkey: String,
    /// Human-readable label (e.g. "Bark browser").
    #[serde(default)]
    pub label: String,
    /// Which NIP-46 methods are auto-approved.
    /// Empty means no policy-controlled method is auto-approved.
    #[serde(default)]
    pub allowed_methods: Vec<String>,
    /// Which event kinds are auto-approved for sign_event.
    /// Empty = all kinds allowed.
    #[serde(default)]
    pub allowed_kinds: Vec<u64>,
    /// Whether to auto-approve matching requests (true) or just OLED-notify (false).
    #[serde(default)]
    pub auto_approve: bool,
}

/// Methods auto-approved on connect when the client provides a valid secret.
/// These are non-signing operations -- safe to grant without physical approval.
pub const CONNECT_SAFE_METHODS: &[&str] = &[
    "nip44_encrypt",
    "nip44_decrypt",
    "nip04_encrypt",
    "nip04_decrypt",
    "get_public_key",
];

/// Methods auto-approved after first physical button approval.
/// Includes signing -- only granted after the user explicitly approves once.
pub const TOFU_SAFE_METHODS: &[&str] = &[
    "sign_event",
    // Naming this in an exact slot only permits the client to present a
    // rendezvous provision request. Firmware pins each fresh request to a
    // physical approval; it is never a silent key-export permission.
    "heartwood_provision_rendezvous",
    "nip44_encrypt",
    "nip44_decrypt",
    "nip04_encrypt",
    "nip04_decrypt",
    "get_public_key",
];

/// Methods an authenticated operator may name in an exact v2 slot policy.
///
/// This deliberately extends, rather than changes, the legacy TOFU surface:
/// a remembered legacy client cannot gain persona-management authority merely
/// by updating firmware. An exact policy is installed through the authenticated
/// management path and is a hard ceiling for a strict slot. The three added
/// extensions only manage personas belonging to the slot's owning master;
/// they never select a caller-supplied signing identity.
pub const EXACT_POLICY_METHODS: &[&str] = &[
    "sign_event",
    "heartwood_provision_rendezvous",
    "heartwood_derive_persona",
    "heartwood_remove_persona",
    "heartwood_rename_persona",
    "nip44_encrypt",
    "nip44_decrypt",
    "nip04_encrypt",
    "nip04_decrypt",
    "get_public_key",
];

/// Bound exact remotely-managed policies so an authenticated but buggy manager
/// cannot grow the persisted NVS blob without limit.
pub const MAX_ALLOWED_KINDS: usize = 64;

/// A validated, exact auto-approval policy supplied by the authenticated
/// operator. `signing_approved` is deliberately not supplied independently: it
/// is derived from whether `sign_event` is present, so the two gates cannot
/// drift into an accidentally broader state.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExactSlotPolicy {
    pub allowed_methods: Vec<String>,
    pub allowed_kinds: Vec<u64>,
    pub auto_approve: bool,
    pub signing_approved: bool,
    /// C4 escalation gate (schema doc §1.5). Additive; defaults false.
    pub escalate: bool,
    /// C4 petition gate (schema doc §1.5). Additive; defaults false.
    pub petition_on_deny: bool,
    /// C5 dual-address child wrap (schema doc §2.1). Additive; defaults false.
    pub audit_child_wrap: bool,
    /// C4/C5 guardian client copy. Additive and opt-in; defaults false.
    pub guardian_notice_wrap: bool,
    /// Identity binding for the child-wrap scan (schema doc §2.1).
    pub bound_identity: Option<String>,
}

/// Validate and canonicalise an exact operator policy before any slot state is
/// mutated. Only methods implemented by Heartwood's standard NIP-46 handler are
/// accepted. Event kinds are meaningful only when `sign_event` is present.
pub fn validate_exact_slot_policy(
    allowed_methods: Vec<String>,
    allowed_kinds: Vec<u64>,
    auto_approve: bool,
) -> Result<ExactSlotPolicy, &'static str> {
    let mut methods = Vec::new();
    for method in allowed_methods {
        if !EXACT_POLICY_METHODS.contains(&method.as_str()) {
            return Err("policy contains an unsupported method");
        }
        if !methods.iter().any(|existing| existing == &method) {
            methods.push(method);
        }
    }

    if allowed_kinds.len() > MAX_ALLOWED_KINDS {
        return Err("policy contains too many event kinds");
    }
    let mut kinds = allowed_kinds;
    kinds.sort_unstable();
    kinds.dedup();

    let signing_approved = methods.iter().any(|method| method == "sign_event");
    if !signing_approved && !kinds.is_empty() {
        return Err("event kinds require sign_event permission");
    }

    Ok(ExactSlotPolicy {
        allowed_methods: methods,
        allowed_kinds: kinds,
        auto_approve,
        signing_approved,
        escalate: false,
        petition_on_deny: false,
        audit_child_wrap: false,
        guardian_notice_wrap: false,
        bound_identity: None,
    })
}

/// Evaluate the policy-controlled part of a slot request. Protocol-wide
/// invariants such as ping/get_public_key are handled by the caller first; this
/// helper is deliberately pure so the firmware's exact deny boundary runs in
/// host CI as well as on the ESP.
pub fn evaluate_slot_policy(
    slot: &ConnectSlot,
    method: &str,
    event_kind: Option<u64>,
) -> ApprovalTier {
    if !slot.allowed_methods.iter().any(|allowed| allowed == method) {
        return if strict_slot_denies_method(slot, method) {
            ApprovalTier::Denied
        } else {
            ApprovalTier::ButtonRequired
        };
    }

    if method == "sign_event" {
        if !slot.signing_approved {
            return if slot.strict_permissions {
                ApprovalTier::Denied
            } else {
                ApprovalTier::ButtonRequired
            };
        }
        if let Some(kind) = event_kind {
            if !slot.allowed_kinds.is_empty() && !slot.allowed_kinds.contains(&kind) {
                return if slot.strict_permissions {
                    ApprovalTier::Denied
                } else {
                    ApprovalTier::ButtonRequired
                };
            }
        }
    }

    if slot.auto_approve {
        ApprovalTier::AutoApprove
    } else {
        ApprovalTier::ButtonRequired
    }
}

/// Exact v2 slots impose a hard method ceiling before legacy Heartwood method
/// invariants (button, OLED notify, or always-auto) are considered.
pub fn strict_slot_denies_method(slot: &ConnectSlot, method: &str) -> bool {
    slot.strict_permissions
        && !slot
            .allowed_methods
            .iter()
            .any(|allowed| allowed == method)
}

/// Grant sign_event after an explicit button/operator approval without
/// broadening any previously configured encryption or event-kind ceiling.
pub fn grant_slot_signing(slot: &mut ConnectSlot) {
    slot.signing_approved = true;
    if !slot
        .allowed_methods
        .iter()
        .any(|method| method == "sign_event")
    {
        slot.allowed_methods.insert(0, "sign_event".to_string());
    }
}

/// Whether a request acts AS an identity with that identity's key and may
/// win approval for it on a card: `sign_event` (both encodings), the four
/// NIP-04/NIP-44 methods, and `get_public_key` when it carries a Heartwood
/// context (caller supplied or a session's active identity). Without a
/// context `get_public_key` is protocol plumbing naming the identity the
/// client already addressed.
pub fn method_uses_identity_key(method: &str, has_context: bool) -> bool {
    match method {
        "sign_event" | "sign_event_compact" | "nip44_encrypt" | "nip44_decrypt"
        | "nip04_encrypt" | "nip04_decrypt" => true,
        "get_public_key" => has_context,
        _ => false,
    }
}

/// Bearer-note methods that act with the served identity's key (sealing a
/// send, deriving an address or claim key). They are scoped like signing but
/// have no identity card of their own: an unapproved identity is refused, and
/// approval comes from a sign or crypto prompt.
pub fn method_uses_served_key(method: &str) -> bool {
    matches!(
        method,
        "heartwood_note_send" | "heartwood_note_address" | "heartwood_note_claim"
    )
}

/// Whether a remote request is scoped to identities approved for its slot:
/// either kind of method above, from a remote client (`has_client`: a relay
/// author, an encrypted USB frame's client key or a bridge-injected client).
/// The direct USB path keeps its physical-possession semantics.
pub fn remote_request_identity_scoped(has_client: bool, method: &str, has_context: bool) -> bool {
    has_client && (method_uses_identity_key(method, has_context) || method_uses_served_key(method))
}

/// Lowercase hex of the first [`IDENTITY_TAG_BYTES`] of an x-only pubkey: the
/// form an approved identity is stored in. Matching a stored tag with another
/// identity needs about 2^64 device derivations, each behind this same gate.
pub fn identity_tag(pubkey: &[u8; 32]) -> [u8; IDENTITY_TAG_BYTES * 2] {
    let mut out = [0u8; IDENTITY_TAG_BYTES * 2];
    lower_hex_into(&pubkey[..IDENTITY_TAG_BYTES], &mut out);
    out
}

fn lower_hex_into(bytes: &[u8], out: &mut [u8]) {
    const DIGITS: &[u8; 16] = b"0123456789abcdef";
    for (i, byte) in bytes.iter().enumerate() {
        out[i * 2] = DIGITS[(byte >> 4) as usize];
        out[i * 2 + 1] = DIGITS[(byte & 0x0f) as usize];
    }
}

/// Whether a slot may act as `pubkey` under its ordinary policy.
///
/// A recorded `bound_identity` (full lowercase hex, as every writer stores it)
/// is always approved, strict slot or not. Otherwise the identity's tag must be
/// in `approved_identities`. An empty list (every slot written before this
/// field existed) approves nothing but the binding, so the first request after
/// upgrade prompts once for whatever identity it uses.
pub fn identity_approved(slot: &ConnectSlot, pubkey: &[u8; 32]) -> bool {
    let mut full = [0u8; 64];
    lower_hex_into(pubkey, &mut full);
    let tag = &full[..IDENTITY_TAG_BYTES * 2];
    slot.bound_identity.as_deref().map(str::as_bytes) == Some(&full[..])
        || slot.approved_identities.as_bytes().chunks(IDENTITY_TAG_BYTES * 2).any(|t| t == tag)
}

/// Fold identity approval into a policy tier: an unapproved identity raises
/// any non-denied tier to a physical prompt (or escalation), whatever
/// `auto_approve` or `allowed_kinds` say. Approval never lifts a tier.
pub fn apply_identity_gate(tier: ApprovalTier, approved: bool) -> ApprovalTier {
    if approved || tier == ApprovalTier::Denied {
        tier
    } else {
        ApprovalTier::ButtonRequired
    }
}

/// Record a physically approved identity on a slot. Returns true when the
/// list changed. Already approved (listed or bound) records nothing, and a
/// full list records nothing either: identities beyond it keep prompting on
/// every request, and nothing is ever evicted.
pub fn record_approved_identity(slot: &mut ConnectSlot, pubkey: &[u8; 32]) -> bool {
    let tag_chars = IDENTITY_TAG_BYTES * 2;
    if identity_approved(slot, pubkey)
        || slot.approved_identities.len() >= MAX_APPROVED_IDENTITIES * tag_chars
        // Only whole tags are ever written; anything else is not ours to extend.
        || slot.approved_identities.len() % tag_chars != 0
    {
        return false;
    }
    slot.approved_identities
        .extend(identity_tag(pubkey).iter().map(|&b| b as char));
    true
}

/// Approval decision for a specific request.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ApprovalTier {
    /// Proceed immediately without user interaction.
    AutoApprove,
    /// Show briefly on OLED (1s) but don't wait for button.
    OledNotify,
    /// Full OLED display with countdown bar, wait for button approval.
    ButtonRequired,
    /// The request is outside the operator-approved policy ceiling.
    Denied,
}

