/// These are non-signing operations -- safe to grant without physical approval.
pub const CONNECT_SAFE_METHODS: &[&str] = &[
    "nip44_encrypt",
    "nip44_decrypt",
    "nip04_encrypt",
    "nip04_decrypt",
    "get_public_key",
];

/// Methods auto-approved after first physical button approval.
/// Includes signing -- only granted after the user explicitly approves once.
pub const TOFU_SAFE_METHODS: &[&str] = &[
    "sign_event",
    // Naming this in an exact slot only permits the client to present a
    // rendezvous provision request. Firmware pins each fresh request to a
    // physical approval; it is never a silent key-export permission.
    "heartwood_provision_rendezvous",
    "nip44_encrypt",
    "nip44_decrypt",
    "nip04_encrypt",
    "nip04_decrypt",
    "get_public_key",
];

/// Methods an authenticated operator may name in an exact v2 slot policy.
///
/// This deliberately extends, rather than changes, the legacy TOFU surface:
/// a remembered legacy client cannot gain persona-management authority merely
/// by updating firmware. An exact policy is installed through the authenticated
/// management path and is a hard ceiling for a strict slot. The three added
/// extensions only manage personas belonging to the slot's owning master;
/// they never select a caller-supplied signing identity.
pub const EXACT_POLICY_METHODS: &[&str] = &[
    "sign_event",
    // Reading the identity list. A strict slot is denied it unless listed;
    // a legacy slot earns it on a LIST IDS card, and a backup of that slot
    // must still validate on import.
    "heartwood_list_identities",
    "heartwood_provision_rendezvous",
    "heartwood_derive_persona",
    "heartwood_remove_persona",
    "heartwood_rename_persona",
    "nip44_encrypt",
    "nip44_decrypt",
    "nip04_encrypt",
    "nip04_decrypt",
    "get_public_key",
];

/// Bound exact remotely-managed policies so an authenticated but buggy manager
/// cannot grow the persisted NVS blob without limit.
pub const MAX_ALLOWED_KINDS: usize = 64;

/// A validated, exact auto-approval policy supplied by the authenticated
/// operator. `signing_approved` is deliberately not supplied independently: it
/// is derived from whether `sign_event` is present, so the two gates cannot
/// drift into an accidentally broader state.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExactSlotPolicy {
    pub allowed_methods: Vec<String>,
    pub allowed_kinds: Vec<u64>,
    pub auto_approve: bool,
    pub signing_approved: bool,
    /// C4 escalation gate (schema doc §1.5). Additive; defaults false.
    pub escalate: bool,
    /// C4 petition gate (schema doc §1.5). Additive; defaults false.
    pub petition_on_deny: bool,
    /// C5 dual-address child wrap (schema doc §2.1). Additive; defaults false.
    pub audit_child_wrap: bool,
    /// C4/C5 guardian client copy. Additive and opt-in; defaults false.
    pub guardian_notice_wrap: bool,
    /// Identity binding for the child-wrap scan (schema doc §2.1).
    pub bound_identity: Option<String>,
}

/// Validate and canonicalise an exact operator policy before any slot state is
/// mutated. Only methods implemented by Heartwood's standard NIP-46 handler are
/// accepted. Event kinds are meaningful only when `sign_event` is present.
pub fn validate_exact_slot_policy(
    allowed_methods: Vec<String>,
    allowed_kinds: Vec<u64>,
    auto_approve: bool,
) -> Result<ExactSlotPolicy, &'static str> {
    let mut methods = Vec::new();
    for method in allowed_methods {
        if !EXACT_POLICY_METHODS.contains(&method.as_str()) {
            return Err("policy contains an unsupported method");
        }
        if !methods.iter().any(|existing| existing == &method) {
            methods.push(method);
        }
    }

    if allowed_kinds.len() > MAX_ALLOWED_KINDS {
        return Err("policy contains too many event kinds");
    }
    let mut kinds = allowed_kinds;
    kinds.sort_unstable();
    kinds.dedup();

    let signing_approved = methods.iter().any(|method| method == "sign_event");
    if !signing_approved && !kinds.is_empty() {
        return Err("event kinds require sign_event permission");
    }

    Ok(ExactSlotPolicy {
        allowed_methods: methods,
        allowed_kinds: kinds,
        auto_approve,
        signing_approved,
        escalate: false,
        petition_on_deny: false,
        audit_child_wrap: false,
        guardian_notice_wrap: false,
        bound_identity: None,
    })
}

/// Evaluate the policy-controlled part of a slot request. Protocol-wide
/// invariants such as ping/get_public_key are handled by the caller first; this
/// helper is deliberately pure so the firmware's exact deny boundary runs in
/// host CI as well as on the ESP.
pub fn evaluate_slot_policy(
    slot: &ConnectSlot,
    method: &str,
    event_kind: Option<u64>,
) -> ApprovalTier {
    if !slot.allowed_methods.iter().any(|allowed| allowed == method) {
        return if strict_slot_denies_method(slot, method) {
            ApprovalTier::Denied
        } else {
            ApprovalTier::ButtonRequired
        };
    }

    if method == "sign_event" {
        if !slot.signing_approved {
            return if slot.strict_permissions {
                ApprovalTier::Denied
            } else {
                ApprovalTier::ButtonRequired
            };
        }
        if let Some(kind) = event_kind {
            if !slot.allowed_kinds.is_empty() && !slot.allowed_kinds.contains(&kind) {
                return if slot.strict_permissions {
                    ApprovalTier::Denied
                } else {
                    ApprovalTier::ButtonRequired
                };
            }
        }
    }

    if slot.auto_approve {
        ApprovalTier::AutoApprove
    } else {
        ApprovalTier::ButtonRequired
    }
}

/// Exact v2 slots impose a hard method ceiling before legacy Heartwood method
/// invariants (button, OLED notify, or always-auto) are considered.
pub fn strict_slot_denies_method(slot: &ConnectSlot, method: &str) -> bool {
    slot.strict_permissions
        && !slot
            .allowed_methods
            .iter()
            .any(|allowed| allowed == method)
}

/// Grant sign_event after an explicit button/operator approval without
/// broadening any previously configured encryption or event-kind ceiling.
pub fn grant_slot_signing(slot: &mut ConnectSlot) {
    slot.signing_approved = true;
    if !slot
        .allowed_methods
        .iter()
        .any(|method| method == "sign_event")
    {
        slot.allowed_methods.insert(0, "sign_event".to_string());
    }
}

/// Whether a request acts AS an identity with that identity's key and may
/// win approval for it on a card: `sign_event` (both encodings), the four
/// NIP-04/NIP-44 methods, and `get_public_key` when it carries a Heartwood
/// context (caller supplied or a session's active identity). Without a
/// context `get_public_key` is protocol plumbing naming the identity the
/// client already addressed.
pub fn method_uses_identity_key(method: &str, has_context: bool) -> bool {
    match method {
        "sign_event" | "sign_event_compact" | "nip44_encrypt" | "nip44_decrypt"
        | "nip04_encrypt" | "nip04_decrypt" => true,
        "get_public_key" => has_context,
        _ => false,
    }
}

/// Bearer-note methods that act with the served identity's key (sealing a
/// send, deriving an address or claim key). They are scoped like signing but
/// have no identity card of their own: an unapproved identity is refused, and
/// approval comes from a sign or crypto prompt.
pub fn method_uses_served_key(method: &str) -> bool {
    matches!(
        method,
        "heartwood_note_send" | "heartwood_note_address" | "heartwood_note_claim"
    )
}

/// Lowercase hex of the first [`IDENTITY_TAG_BYTES`] of an x-only pubkey: the
/// form an approved identity is stored in. Matching a stored tag with another
/// identity needs about 2^64 device derivations, each behind this same gate.
pub fn identity_tag(pubkey: &[u8; 32]) -> [u8; IDENTITY_TAG_BYTES * 2] {
    let mut out = [0u8; IDENTITY_TAG_BYTES * 2];
    lower_hex_into(&pubkey[..IDENTITY_TAG_BYTES], &mut out);
    out
}

fn lower_hex_into(bytes: &[u8], out: &mut [u8]) {
    const DIGITS: &[u8; 16] = b"0123456789abcdef";
    for (i, byte) in bytes.iter().enumerate() {
        out[i * 2] = DIGITS[(byte >> 4) as usize];
        out[i * 2 + 1] = DIGITS[(byte & 0x0f) as usize];
    }
}

/// Whether a slot may act as `pubkey` under its ordinary policy.
///
/// A recorded `bound_identity` (full lowercase hex, as every writer stores it)
/// is always approved, strict slot or not. Otherwise the identity's tag must be
/// in `approved_identities`. An empty list (every slot written before this
/// field existed) approves nothing but the binding, so the first request after
/// upgrade prompts once for whatever identity it uses.
pub fn identity_approved(slot: &ConnectSlot, pubkey: &[u8; 32]) -> bool {
    if slot.client_grants.is_some() { return false; } // A G4 decision requires a client key.
    let mut full = [0u8; 64];
    lower_hex_into(pubkey, &mut full);
    let tag = &full[..IDENTITY_TAG_BYTES * 2];
    slot.bound_identity.as_deref().map(str::as_bytes) == Some(&full[..])
        || slot.approved_identities.as_bytes().chunks(IDENTITY_TAG_BYTES * 2).any(|t| t == tag)
}

/// Resolve persona consent for the actual authenticated client credential.
pub fn client_identity_approved(slot: &ConnectSlot, client: Option<&str>, identity: &[u8; 32]) -> bool {
    match &slot.client_grants {
        None => identity_approved(slot, identity),
        Some(grants) => client.and_then(decode_client_key).is_some_and(|key| grants.allows(&key, identity)),
    }
}

pub fn decode_client_key(key: &str) -> Option<[u8; 32]> {
    if key.len() != 64 || !key.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f')) { return None; }
    crate::hex::hex_decode(key).ok()?.try_into().ok()
}

/// Only a physically/operator approved request may call this mutation.
pub fn record_client_identity(slot: &mut ConnectSlot, client: &str, identity: &[u8; 32]) -> bool {
    match &mut slot.client_grants {
        None => record_approved_identity(slot, identity),
        Some(grants) => decode_client_key(client).and_then(|key| grants.approve(&key, identity).ok()).unwrap_or(false),
    }
}

/// The card must say approve-once when remembered-consent capacity is full.
pub fn can_record_client_identity(slot: &ConnectSlot) -> bool {
    slot.client_grants.as_ref().map_or(
        slot.approved_identities.len() < MAX_APPROVED_IDENTITIES * IDENTITY_TAG_BYTES * 2,
        |g| g.grant_count() < 16,
    )
}

/// Fold identity approval into a policy tier: an unapproved identity raises
/// any non-denied tier to a physical prompt (or escalation), whatever
/// `auto_approve` or `allowed_kinds` say. Approval never lifts a tier.
pub fn apply_identity_gate(tier: ApprovalTier, approved: bool) -> ApprovalTier {
    if approved || tier == ApprovalTier::Denied {
        tier
    } else {
        ApprovalTier::ButtonRequired
    }
}

/// Record a physically approved identity on a slot. Returns true when the
/// list changed. Already approved (listed or bound) records nothing, and a
/// full list records nothing either: identities beyond it keep prompting on
/// every request, and nothing is ever evicted.
pub fn record_approved_identity(slot: &mut ConnectSlot, pubkey: &[u8; 32]) -> bool {
    if slot.client_grants.is_some() { return false; }
    let tag_chars = IDENTITY_TAG_BYTES * 2;
    if identity_approved(slot, pubkey)
        || slot.approved_identities.len() >= MAX_APPROVED_IDENTITIES * tag_chars
        // Only whole tags are ever written; anything else is not ours to extend.
        || slot.approved_identities.len() % tag_chars != 0
    {
        return false;
    }
    slot.approved_identities
        .extend(identity_tag(pubkey).iter().map(|&b| b as char));
    true
}

/// The approved identity tags of a slot, for read-only display.
pub fn approved_identity_tags(slot: &ConnectSlot) -> Vec<&str> {
    slot.approved_identities
        .as_bytes()
        .chunks(IDENTITY_TAG_BYTES * 2)
        .filter_map(|tag| core::str::from_utf8(tag).ok())
        .collect()
}

/// Change a slot's identity binding. A different binding clears the approved
/// identity list: approvals were given for the pairing as it was bound, and
/// the new binding is itself approved. Returns true when the binding changed.
pub fn set_slot_bound_identity(slot: &mut ConnectSlot, bound_identity: Option<String>) -> bool {
    if slot.bound_identity == bound_identity {
        return false;
    }
    slot.bound_identity = bound_identity;
    slot.approved_identities.clear();
    if let Some(grants) = &mut slot.client_grants { grants.clear_identities(); }
    true
}

/// Parse an identity named by a management caller: a 64-character hex x-only
/// pubkey (either case) or an `npub1...`. Anything else is refused.
pub fn parse_identity_pubkey(input: &str) -> Result<[u8; 32], &'static str> {
    const INVALID: &str = "invalid_identity: expected a 64-hex pubkey or an npub";
    if input.len() == 64 && input.bytes().all(|b| b.is_ascii_hexdigit()) {
        return crate::hex::hex_decode(input)
            .ok()
            .and_then(|bytes| bytes.try_into().ok())
            .ok_or(INVALID);
    }
    crate::encoding::decode_npub(input).ok_or(INVALID)
}

/// Whether `pubkey` is the slot's recorded binding. Compared without regard to
/// case, so a binding written in any case is never mistaken for a revocable
/// approval.
fn is_bound_identity(slot: &ConnectSlot, pubkey: &[u8; 32]) -> bool {
    slot.bound_identity
        .as_deref()
        .is_some_and(|bound| bound.eq_ignore_ascii_case(&crate::hex::hex_encode(pubkey)))
}

/// An identity named for revocation: a whole pubkey, or the 16-hex tag
/// `list_clients` shows for an approval whose pubkey the caller cannot name.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IdentityRef {
    Pubkey([u8; 32]),
    /// Lowercase hex, as [`identity_tag`] writes it.
    Tag([u8; IDENTITY_TAG_BYTES * 2]),
}

impl IdentityRef {
    /// The stored tag this identity is approved under.
    pub fn tag(&self) -> [u8; IDENTITY_TAG_BYTES * 2] {
        match self {
            IdentityRef::Pubkey(pubkey) => identity_tag(pubkey),
            IdentityRef::Tag(tag) => *tag,
        }
    }

    /// Whether `pubkey` is this identity: the whole key, or any key with this
    /// tag.
    pub fn matches(&self, pubkey: &[u8; 32]) -> bool {
        match self {
            IdentityRef::Pubkey(own) => own == pubkey,
            IdentityRef::Tag(tag) => identity_tag(pubkey) == *tag,
        }
    }
}

/// Parse an identity named for revocation: a 64-hex pubkey or an npub (as
/// [`parse_identity_pubkey`]), or a 16-hex identity tag in either case.
pub fn parse_identity_ref(input: &str) -> Result<IdentityRef, &'static str> {
    const INVALID: &str = "invalid_identity: expected a 64-hex pubkey, an npub or a 16-hex identity tag";
    let tag_chars = IDENTITY_TAG_BYTES * 2;
    if input.len() == tag_chars && input.bytes().all(|b| b.is_ascii_hexdigit()) {
        let mut tag = [0u8; IDENTITY_TAG_BYTES * 2];
        for (out, byte) in tag.iter_mut().zip(input.bytes()) {
            *out = byte.to_ascii_lowercase();
        }
        return Ok(IdentityRef::Tag(tag));
    }
    parse_identity_pubkey(input).map(IdentityRef::Pubkey).map_err(|_| INVALID)
}

/// Whether `identity` names the slot's binding: the whole key for a pubkey,
/// the binding's tag for a tag. Case-insensitive, so a binding written in any
/// case is never mistaken for a revocable approval.
fn names_bound_identity(slot: &ConnectSlot, identity: &IdentityRef) -> bool {
    let Some(bound) = slot.bound_identity.as_deref() else {
        return false;
    };
    match identity {
        IdentityRef::Pubkey(pubkey) => is_bound_identity(slot, pubkey),
        IdentityRef::Tag(tag) => bound
            .as_bytes()
            .get(..IDENTITY_TAG_BYTES * 2)
            .is_some_and(|prefix| prefix.eq_ignore_ascii_case(tag)),
    }
}

/// What revoking one approved identity did.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RevokeIdentity {
    /// Its tag was in the approved list and is gone.
    Removed,
    /// It was not in the list: nothing changed.
    Absent,
    /// It is the slot's binding, which is approved without a list entry.
    /// Removing a tag would leave it approved, so nothing is changed.
    Bound,
}

/// Withdraw one identity's approval from a slot, leaving the pairing, its
/// methods, kinds, binding and client keys alone. The next request as that
/// identity meets the identity gate's card again. Every copy of its tag goes,
/// and only whole tags are compared.
pub fn revoke_approved_identity(slot: &mut ConnectSlot, pubkey: &[u8; 32]) -> RevokeIdentity {
    revoke_approved_identity_ref(slot, &IdentityRef::Pubkey(*pubkey))
}

/// [`revoke_approved_identity`] for a pubkey or a tag. A tag that matches the
/// binding's tag is refused like the binding itself.
pub fn revoke_approved_identity_ref(slot: &mut ConnectSlot, identity: &IdentityRef) -> RevokeIdentity {
    if slot.client_grants.is_some() {
        return revoke_client_identity_ref(slot, None, identity);
    }
    if names_bound_identity(slot, identity) {
        return RevokeIdentity::Bound;
    }
    let tag = identity.tag();
    let kept: Vec<u8> = slot
        .approved_identities
        .as_bytes()
        .chunks(IDENTITY_TAG_BYTES * 2)
        .filter(|chunk| *chunk != &tag[..])
        .flatten()
        .copied()
        .collect();
    if kept.len() == slot.approved_identities.len() {
        return RevokeIdentity::Absent;
    }
    // A removed chunk is whole ASCII, so what is left is still valid UTF-8.
    match String::from_utf8(kept) {
        Ok(kept) => {
            slot.approved_identities = kept;
            RevokeIdentity::Removed
        }
        Err(_) => RevokeIdentity::Absent,
    }
}

/// Withdraw consent for a selected credential, or all credentials in the slot.
/// A tag deliberately withdraws every matching exact or grandfathered identity.
pub fn revoke_client_identity_ref(slot: &mut ConnectSlot, client: Option<&str>, identity: &IdentityRef) -> RevokeIdentity {
    let Some(grants) = &mut slot.client_grants else { return revoke_approved_identity_ref(slot, identity); };
    let clients = match client { Some(key) => decode_client_key(key).into_iter().collect(), None => grants.client_keys() };
    let mut changed = false;
    for key in clients {
        let identities = match identity {
            IdentityRef::Pubkey(pubkey) => vec![*pubkey],
            IdentityRef::Tag(tag) => {
                let mut identities: Vec<_> = grants.approved_keys(&key).into_iter().filter(|id| identity.matches(id)).collect();
                if let Ok(bytes) = crate::hex::hex_decode(core::str::from_utf8(tag).unwrap_or("")) {
                    if bytes.len() == 8 {
                        let mut placeholder = [0u8; 32];
                        placeholder[..8].copy_from_slice(&bytes);
                        identities.push(placeholder);
                    }
                }
                identities
            }
        };
        for pubkey in identities { changed |= grants.revoke_identity(&key, &pubkey).unwrap_or(false); }
    }
    if changed { RevokeIdentity::Removed } else { RevokeIdentity::Absent }
}

/// Withdraw every recorded identity approval from a slot. The binding, if any,
/// stays approved: change it through [`set_slot_bound_identity`]. True when
/// the list changed.
pub fn clear_approved_identities(slot: &mut ConnectSlot) -> bool {
    if let Some(grants) = &mut slot.client_grants {
        slot.approved_identities.clear();
        return grants.clear_identities();
    }
    if slot.approved_identities.is_empty() {
        return false;
    }
    slot.approved_identities.clear();
    true
}

/// Whether a live approve-once verdict falls with an identity approval
/// withdrawn from `slot`: it was given to one of the slot's client keys for an
/// identity-scoped request, and for `revoked` (the whole key, or any key with
/// the tag), or (`None`, clearing
/// the list) for any identity but the slot's binding, which stays approved.
/// A verdict for a request that uses no identity key is untouched.
pub fn verdict_withdrawn(
    slot: &ConnectSlot,
    client_pubkey: &str,
    granted: Option<&[u8; 32]>,
    revoked: Option<&IdentityRef>,
) -> bool {
    let Some(granted) = granted else {
        return false;
    };
    slot_authorizes(slot, client_pubkey)
        && match revoked {
            Some(revoked) => revoked.matches(granted),
            None => slot.client_grants.is_some() || !is_bound_identity(slot, granted),
        }
}

/// Add one method to a legacy slot's auto-approved set after an explicit
/// physical approval, the way [`grant_slot_signing`] adds `sign_event`.
pub fn grant_slot_method(slot: &mut ConnectSlot, method: &str) -> bool {
    if slot.allowed_methods.iter().any(|allowed| allowed == method) {
        return false;
    }
    slot.allowed_methods.push(method.to_string());
    true
}

/// Which physical card the gate asks for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CardKind {
    /// `ALLOW AS <identity>?`: approval lets this pairing act as the identity
    /// for every method, and is recorded unless the list is full (`record`).
    AllowAs { record: bool },
    /// `NPUB AS <identity>?`: discloses one derived pubkey, records nothing.
    NpubAs,
    /// `LIST IDS FOR <app>?`: approval adds `heartwood_list_identities` to a
    /// legacy slot's allowed methods.
    ListIds,
    /// `SWITCH TO <identity>?`: the physical hold `heartwood_switch` always
    /// needed, which now also approves the target identity like `ALLOW AS`
    /// (recorded unless the list is full, `record`). A switch policy lets
    /// through silently, or a guardian verdict, is not a card and records
    /// nothing.
    SwitchTo { record: bool },
}

/// The gate's decision for one request.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Gate {
    /// Nothing more from the gate: the policy tier governs as before.
    Allow,
    /// Stop for this physical card first.
    Card(CardKind),
    /// Refuse.
    Deny,
}

/// Everything the gate decides from. Pure data, so the relay's pre-dispatch
/// decision and the handler's decision are the same function of the same
/// facts.
#[derive(Debug, Clone, Copy)]
pub struct GateRequest<'a> {
    /// A remote client (relay author, encrypted USB client key or a
    /// bridge-injected client). Direct USB is never gated here.
    pub has_client: bool,
    pub client_pubkey: Option<&'a str>,
    /// The client's slot; `None` for an unbound client.
    pub slot: Option<&'a ConnectSlot>,
    pub method: &'a str,
    /// The slot policy tier (`PolicyEngine::check`, pins applied).
    pub tier: ApprovalTier,
    /// The caller supplied a top-level Heartwood context.
    pub explicit_context: bool,
    /// A context applies: explicit, or a session's active identity.
    pub has_context: bool,
    /// The x-only pubkey of the key the request will use, when it uses one.
    pub identity: Option<&'a [u8; 32]>,
    /// A live guardian approve-once verdict covers this request (and, for an
    /// identity-scoped request, this identity).
    pub verdict: bool,
}

/// NIP-04/NIP-44 methods, which a remote client may use only when policy
/// auto-approves them.
fn is_crypto_method(method: &str) -> bool {
    matches!(method, "nip44_encrypt" | "nip44_decrypt" | "nip04_encrypt" | "nip04_decrypt")
}

/// The single identity and list-identities gate for a remote request.
///
/// In order: direct USB is never gated; a policy denial or an explicit
/// context on a strict slot is refused; an unbound client is refused for any
/// identity-scoped method or identity listing; a crypto method policy would
/// only prompt for is refused (a remote crypto oracle is never offered on a
/// card); `heartwood_list_identities` needs a card unless the slot lists it;
/// `heartwood_switch` policy would prompt for is the `SWITCH TO` card; an
/// identity-scoped method acting as an unapproved identity needs a card.
pub fn gate_request(request: &GateRequest<'_>) -> Gate {
    if !request.has_client {
        return Gate::Allow;
    }
    if request.tier == ApprovalTier::Denied {
        return Gate::Deny;
    }
    let method = request.method;
    let lists = method == "heartwood_list_identities";
    let switch = method == "heartwood_switch";
    let scoped = method_uses_identity_key(method, request.has_context) || method_uses_served_key(method);
    let Some(slot) = request.slot else {
        return if scoped || lists || switch { Gate::Deny } else { Gate::Allow };
    };
    if slot.strict_permissions && request.explicit_context {
        return Gate::Deny;
    }
    if is_crypto_method(method) && request.tier == ApprovalTier::ButtonRequired {
        return Gate::Deny;
    }
    if lists {
        return if request.verdict || slot.allowed_methods.iter().any(|allowed| allowed == method) {
            Gate::Allow
        } else {
            Gate::Card(CardKind::ListIds)
        };
    }
    let record = can_record_client_identity(slot);
    if switch {
        return if !request.verdict && request.tier == ApprovalTier::ButtonRequired {
            Gate::Card(CardKind::SwitchTo { record })
        } else {
            Gate::Allow
        };
    }
    if !scoped {
        return Gate::Allow;
    }
    let Some(identity) = request.identity else {
        return Gate::Deny;
    };
    if request.verdict || client_identity_approved(slot, request.client_pubkey, identity) {
        Gate::Allow
    } else if method == "get_public_key" {
        Gate::Card(CardKind::NpubAs)
    } else {
        Gate::Card(CardKind::AllowAs { record })
    }
}

/// The tier a gate decision stands for, for callers that plan around tiers
/// (relay escalation, rollback snapshots, audit outcomes).
pub fn gate_tier(gate: Gate, tier: ApprovalTier) -> ApprovalTier {
    match gate {
        Gate::Allow => tier,
        Gate::Card(_) => ApprovalTier::ButtonRequired,
        Gate::Deny => ApprovalTier::Denied,
    }
}

/// What a deferred card showed, kept with the ask so its resumed dispatch can
/// prove the hold still answers the same question.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct ShownCard {
    /// The gate card it was (a sign card carrying ALLOW AS counts as
    /// `AllowAs`), or `None` for a policy card: HOLD TO SIGN or the method's
    /// own card.
    pub card: Option<CardKind>,
    /// The identity the card named and the request would act as: the
    /// effective identity, or a switch's target. `None` when the request uses
    /// no identity key.
    pub identity: Option<[u8; 32]>,
}

/// How a resumed ask may proceed on a completed hold.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ResumeDecision {
    /// The hold answers exactly this request as it now stands.
    Proceed,
    /// The request would now act as a different identity from the card's:
    /// refuse, and never act on or record the new identity.
    IdentityChanged,
    /// The request now needs a different card from the one held: answer
    /// "send the request again" so it meets the right card.
    CardChanged,
    /// A gate card was held (the identity is now approved), but the method's
    /// own card has not been shown: answer "send the request again".
    OwnCardNext,
}

/// Compare what a card showed with what its resumed request now needs.
/// `card_now` is the gate card the request needs now (`None` for none or a
/// policy card); `identity_now` the identity it would act as now; `own_card`
/// whether the method's own card is still due after any gate card.
///
/// `recorded` says the slot itself now holds what the shown card grants: the
/// identity in its approved list (or binding) for `ALLOW AS`, the method in its
/// allowed set for `LIST IDS`. That is how a batch reads after its first ask
/// recorded the grant: the later asks need no card, and the one hold answers
/// them too. A verdict or anything else that merely lets a request through is
/// not `recorded`, so it still answers "send the request again".
pub fn resume_decision(
    shown: &ShownCard,
    card_now: Option<CardKind>,
    identity_now: Option<&[u8; 32]>,
    own_card: bool,
    recorded: bool,
) -> ResumeDecision {
    if shown.identity.as_ref() != identity_now {
        return ResumeDecision::IdentityChanged;
    }
    let granted_by_this_hold = card_now.is_none()
        && recorded
        && matches!(shown.card, Some(CardKind::AllowAs { .. } | CardKind::ListIds));
    let kind = |card: Option<CardKind>| {
        card.map(|card| match card {
            CardKind::AllowAs { .. } => 1,
            CardKind::NpubAs => 2,
            CardKind::ListIds => 3,
            CardKind::SwitchTo { .. } => 4,
        })
    };
    if kind(shown.card) != kind(card_now) && !granted_by_this_hold {
        return ResumeDecision::CardChanged;
    }
    if shown.card.is_some() && own_card {
        return ResumeDecision::OwnCardNext;
    }
    ResumeDecision::Proceed
}

/// Whether an approve-once verdict granted for `granted` (the identity the
/// guardian's notice named, if any) covers a request acting as `requested`.
/// A request that uses no identity key is covered by the method match alone;
/// an identity-scoped one only by a verdict for exactly its identity.
pub fn verdict_covers_identity(granted: Option<&[u8; 32]>, requested: Option<&[u8; 32]>) -> bool {
    requested.map_or(true, |requested| granted == Some(requested))
}

/// A marker for an ask's batching key: asks for different cards never share
/// one hold.
pub fn card_batch_marker(card: Option<CardKind>) -> &'static str {
    match card {
        None => "",
        Some(CardKind::AllowAs { .. }) => "#allow",
        Some(CardKind::NpubAs) => "#npub",
        Some(CardKind::ListIds) => "#list",
        Some(CardKind::SwitchTo { .. }) => "#switch",
    }
}

/// Sanitise one connection slot from a backup before import: signing and kind
/// ceilings are stripped (a restore never carries silent signing), then the
/// method ceiling is re-validated. Identity approvals and the bound flag are
/// kept. Returns whether signing was stripped.
pub fn sanitise_imported_slot(slot: &mut ConnectSlot) -> Result<bool, &'static str> {
    if slot.client_grants.is_none() {
        slot.client_grants = Some(crate::client_grants::GrantSnapshot::from_legacy(slot).map_err(|_| "invalid saved client authority")?);
    }
    clear_approved_identities(slot);
    let had_signing =
        slot.signing_approved || slot.allowed_methods.iter().any(|m| m == "sign_event");
    slot.signing_approved = false;
    slot.allowed_methods.retain(|m| m != "sign_event");
    // Kind ceilings are meaningless without sign_event (and the validator
    // rejects the combination), so they go with it.
    slot.allowed_kinds.clear();
    let policy =
        validate_exact_slot_policy(slot.allowed_methods.clone(), Vec::new(), slot.auto_approve)?;
    slot.allowed_methods = policy.allowed_methods;
    slot.allowed_kinds = policy.allowed_kinds;
    slot.auto_approve = policy.auto_approve;
    Ok(had_signing)
}

/// Approval decision for a specific request.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ApprovalTier {
    /// Proceed immediately without user interaction.
    AutoApprove,
    /// Show briefly on OLED (1s) but don't wait for button.
    OledNotify,
    /// Full OLED display with countdown bar, wait for button approval.
    ButtonRequired,
    /// The request is outside the operator-approved policy ceiling.
    Denied,
}

