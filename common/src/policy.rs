/// Validate and migrate one complete master's table before serving requests.
/// Existing full-format snapshots are never reconstructed from legacy tags.
/// All candidate snapshots are prepared before any live slot is mutated.
pub fn validate_slot_table(slots: &[ConnectSlot]) -> Result<(), &'static str> {
    if slots.len() > MAX_CONNECT_SLOTS as usize { return Err("too many slots"); }
    for (position, slot) in slots.iter().enumerate() {
        if slots[..position].iter().any(|s| s.slot_index == slot.slot_index || s.secret == slot.secret) {
            return Err("duplicate slot or credential");
        }
        crate::slot_codec::validate_slot(slot)?;
    }
    Ok(())
}

pub fn migrate_client_grants(slots: &mut [ConnectSlot]) -> Result<bool, &'static str> {
    validate_slot_table(slots)?;
    let mut prepared = Vec::new();
    for slot in slots.iter() {
        prepared.push(if slot.client_grants.is_none() {
            Some(crate::client_grants::GrantSnapshot::from_legacy(slot).map_err(|_| "invalid legacy consent")?)
        } else { None });
    }
    let mut changed = false;
    for (slot, snapshot) in slots.iter_mut().zip(prepared) {
        if let Some(snapshot) = snapshot {
            slot.client_grants = Some(snapshot);
            slot.approved_identities.clear();
            changed = true;
        }
    }
    Ok(changed)
}

/// True if `pubkey` is authorised for this slot -- either the current binding
/// or any pubkey that has previously paired with the slot secret.
pub fn slot_authorizes(slot: &ConnectSlot, pubkey: &str) -> bool {
    slot.current_pubkey.as_deref() == Some(pubkey)
        || slot.authorized_pubkeys.iter().any(|p| p == pubkey)
}

/// How a `connect` request's client key relates to the slot's current binding
/// and its retained authority. Computed from the slot's pre-mutation device
/// state, not from whatever state the client last observed.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ConnectPubkeyClass {
    /// The pubkey is already the slot's current binding.
    Current,
    /// Not current, but present in `authorized_pubkeys`; a still-authorised
    /// client of the same pairing.
    Known,
    /// No current key, no retained keys, and `was_bound` is false: first-ever
    /// binding of the slot.
    FirstUse,
    /// Neither current nor retained, and the slot is not first-use.
    Unknown,
}

/// Classify a `connect` client key against `slot` without mutating it.
///
/// `Known` reuses [`slot_authorizes`]; because `Current` is checked first this
/// means "retained, not current". `was_bound == false` with retained keys is
/// `Unknown` only for a key not in that retained set: a legacy blob that lost
/// `was_bound` must not let a stranger inherit an existing pairing's
/// authority, while keys already present in `authorized_pubkeys` still
/// classify as `Known`.
pub fn classify_connect_pubkey(slot: &ConnectSlot, pubkey: &str) -> ConnectPubkeyClass {
    if slot.current_pubkey.as_deref() == Some(pubkey) {
        ConnectPubkeyClass::Current
    } else if slot_authorizes(slot, pubkey) {
        ConnectPubkeyClass::Known
    } else if slot.current_pubkey.is_none()
        && !slot.was_bound
        && slot.authorized_pubkeys.is_empty()
    {
        ConnectPubkeyClass::FirstUse
    } else {
        ConnectPubkeyClass::Unknown
    }
}

/// Return current client keys explicitly opted in to receive a guardian's
/// C4/C5 copy. A matching identity alone is not enough: the policy flag keeps
/// child audit readers from becoming guardian-notice recipients by accident.
/// The relay validates the returned public-key strings before use.
pub fn guardian_notice_recipient_pubkeys<'a>(
    slots: &'a [ConnectSlot],
    guardian_identity: &str,
) -> Vec<&'a str> {
    slots
        .iter()
        .filter(|slot| {
            slot.guardian_notice_wrap
                && slot.bound_identity.as_deref() == Some(guardian_identity)
        })
        .filter_map(|slot| slot.current_pubkey.as_deref())
        .collect()
}

/// Remove a stale remembered client key without changing the slot credential
/// or policy. The current key is deliberately not removable here: it is the
/// live holder and must be evicted by revoking/rotating the whole slot.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RemoveAuthorizedPubkey {
    Removed,
    Current,
    Missing,
}

pub fn remove_authorized_pubkey(
    slot: &mut ConnectSlot,
    pubkey: &str,
) -> RemoveAuthorizedPubkey {
    if slot.current_pubkey.as_deref() == Some(pubkey) {
        return RemoveAuthorizedPubkey::Current;
    }
    let before = slot.authorized_pubkeys.len();
    slot.authorized_pubkeys.retain(|candidate| candidate != pubkey);
    if let (Some(grants), Some(key)) = (&mut slot.client_grants, decode_client_key(pubkey)) { let _ = grants.remove_client(&key); }
    if slot.authorized_pubkeys.len() < before {
        RemoveAuthorizedPubkey::Removed
    } else {
        RemoveAuthorizedPubkey::Missing
    }
}

/// Authorise `pubkey` on a slot: make it the current binding and remember it in
/// `authorized_pubkeys`. The outgoing `current_pubkey` is preserved in the set,
/// so an earlier device stays auto-approved instead of being evicted. The set
/// is de-duplicated and FIFO-capped at [`MAX_AUTHORIZED_PUBKEYS`].
pub fn authorize_pubkey_on_slot(slot: &mut ConnectSlot, pubkey: &str) -> bool {
    if let Some(grants) = &mut slot.client_grants {
        let Some(key) = decode_client_key(pubkey) else { return false; };
        if grants.add_client(key).is_err() { return false; }
        slot.was_bound = true;
        if let Some(previous) = slot.current_pubkey.take() {
            if !slot.authorized_pubkeys.contains(&previous) { slot.authorized_pubkeys.push(previous); }
        }
        if !slot.authorized_pubkeys.iter().any(|p| p == pubkey) { slot.authorized_pubkeys.push(pubkey.to_string()); }
        slot.current_pubkey = Some(pubkey.to_string());
        return true;
    }
    // A client key this slot has never authorised, replacing one it had, is a
    // new holder of the credential: identity approvals were given to the old
    // one and do not carry over. A key that paired before keeps them, so two
    // devices sharing one slot do not reset each other.
    if (slot.was_bound || slot.current_pubkey.is_some() || !slot.authorized_pubkeys.is_empty())
        && !slot_authorizes(slot, pubkey)
    {
        slot.approved_identities.clear();
    }
    slot.was_bound = true;
    if let Some(prev) = slot.current_pubkey.take() {
        if prev != pubkey {
            push_authorized(slot, prev);
        }
    }
    push_authorized(slot, pubkey.to_string());
    slot.current_pubkey = Some(pubkey.to_string());
    true
}

/// Move `pubkey` onto exactly one slot within a master, then authorise it there.
///
/// A client key must never inherit whichever policy happens to appear first in
/// the slot vector. Before binding the target, remove that key from every other
/// slot's current and retained-authority fields. Other clients sharing those
/// slots are preserved. Returns false without mutation when `slot_index` does
/// not exist.
pub fn authorize_pubkey_on_unique_slot(
    slots: &mut [ConnectSlot],
    slot_index: u8,
    pubkey: &str,
) -> bool {
    let Some(target_pos) = slots.iter().position(|slot| slot.slot_index == slot_index) else {
        return false;
    };

    let mut target = slots[target_pos].clone();
    if !authorize_pubkey_on_slot(&mut target, pubkey) { return false; }
    for (position, slot) in slots.iter_mut().enumerate() {
        if position == target_pos {
            continue;
        }
        if slot.current_pubkey.as_deref() == Some(pubkey) {
            slot.current_pubkey = None;
        }
        slot.authorized_pubkeys.retain(|candidate| candidate != pubkey);
        if let (Some(grants), Some(key)) = (&mut slot.client_grants, decode_client_key(pubkey)) { let _ = grants.remove_client(&key); }
    }

    slots[target_pos] = target;
    true
}

/// Remove every client pubkey that is authorised by more than one slot.
///
/// This is the fail-closed boot migration for state written before unique slot
/// ownership was enforced. Picking the first or last slot could silently retain
/// the broader policy; removing an ambiguous key from all slots forces the app
/// to prove possession of exactly one slot secret on its next connect. Returns
/// true when any authority field changed.
pub fn remove_ambiguous_pubkeys(slots: &mut [ConnectSlot]) -> bool {
    let mut owners: Vec<(String, usize)> = Vec::new();
    let mut ambiguous: Vec<String> = Vec::new();

    for (position, slot) in slots.iter().enumerate() {
        for pubkey in slot
            .current_pubkey
            .iter()
            .chain(slot.authorized_pubkeys.iter())
        {
            if ambiguous.iter().any(|candidate| candidate == pubkey) {
                continue;
            }
            match owners.iter().find(|(candidate, _)| candidate == pubkey) {
                Some((_, owner)) if *owner != position => ambiguous.push(pubkey.clone()),
                Some(_) => {}
                None => owners.push((pubkey.clone(), position)),
            }
        }
    }

    if ambiguous.is_empty() {
        return false;
    }

    let mut changed = false;
    for slot in slots.iter_mut() {
        if slot
            .current_pubkey
            .as_ref()
            .map(|pubkey| ambiguous.iter().any(|candidate| candidate == pubkey))
            .unwrap_or(false)
        {
            slot.current_pubkey = None;
            changed = true;
        }
        let before = slot.authorized_pubkeys.len();
        slot.authorized_pubkeys
            .retain(|pubkey| !ambiguous.iter().any(|candidate| candidate == pubkey));
        if let Some(grants) = &mut slot.client_grants {
            for key in ambiguous.iter().filter_map(|k| decode_client_key(k)) { let _ = grants.remove_client(&key); }
        }
        changed |= slot.authorized_pubkeys.len() != before;
    }
    changed
}

/// Add a pubkey to a slot's authorised set (de-duplicated, FIFO-capped).
fn push_authorized(slot: &mut ConnectSlot, pubkey: String) {
    if slot.authorized_pubkeys.iter().any(|p| *p == pubkey) {
        return;
    }
    while slot.authorized_pubkeys.len() >= MAX_AUTHORIZED_PUBKEYS {
        slot.authorized_pubkeys.remove(0);
    }
    slot.authorized_pubkeys.push(pubkey);
}

/// Find a slot that authorises this client pubkey (current binding or set).
pub fn find_slot_by_pubkey<'a>(slots: &'a [ConnectSlot], pubkey: &str) -> Option<&'a ConnectSlot> {
    slots.iter().find(|s| slot_authorizes(s, pubkey))
}

/// Find a mutable slot that authorises this client pubkey (current binding or set).
pub fn find_slot_by_pubkey_mut<'a>(
    slots: &'a mut [ConnectSlot],
    pubkey: &str,
) -> Option<&'a mut ConnectSlot> {
    slots.iter_mut().find(|s| slot_authorizes(s, pubkey))
}

/// Find a slot by its secret using constant-time comparison.
/// Always iterates all slots to prevent timing-based slot identification.
/// Returns the first matching slot (lowest index).
pub fn find_slot_by_secret<'a>(slots: &'a [ConnectSlot], secret: &str) -> Option<&'a ConnectSlot> {
    let mut matched: Option<usize> = None;
    for (i, slot) in slots.iter().enumerate() {
        if constant_time_eq_str(&slot.secret, secret) && matched.is_none() {
            matched = Some(i);
        }
    }
    matched.map(|i| &slots[i])
}

/// Find a mutable slot by its secret using constant-time comparison.
/// Always iterates all slots to prevent timing-based slot identification.
/// Returns the first matching slot (lowest index).
pub fn find_slot_by_secret_mut<'a>(
    slots: &'a mut [ConnectSlot],
    secret: &str,
) -> Option<&'a mut ConnectSlot> {
    let mut matched: Option<usize> = None;
    for (i, slot) in slots.iter().enumerate() {
        if constant_time_eq_str(&slot.secret, secret) && matched.is_none() {
            matched = Some(i);
        }
    }
    matched.map(move |i| &mut slots[i])
}

/// Find the next available slot index (0-15). Returns None if all 16 are occupied.
pub fn next_slot_index(slots: &[ConnectSlot]) -> Option<u8> {
    for i in 0..MAX_CONNECT_SLOTS {
        if !slots.iter().any(|s| s.slot_index == i) {
            return Some(i);
        }
    }
    None
}

/// Create a redacted copy of a slot (secret replaced with empty string).
pub fn redact_slot(slot: &ConnectSlot) -> ConnectSlot {
    ConnectSlot {
        secret: String::new(),
        client_grants: None,
        ..slot.clone()
    }
}

/// Constant-time string equality (prevents timing attacks on secret comparison).
fn constant_time_eq_str(a: &str, b: &str) -> bool {
    let a = a.as_bytes();
    let b = b.as_bytes();
    if a.len() != b.len() {
        return false;
    }
    let mut diff = 0u8;
    for (x, y) in a.iter().zip(b.iter()) {
        diff |= x ^ y;
    }
    diff == 0
}

