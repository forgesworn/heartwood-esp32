//! Host check of the actual ESP8266 signing source against its frozen boot POST.
//! The bytes below predate the k256 0.14 migration (selftest.rs, k256 0.13).
#![cfg(feature = "k256-backend")]

#[path = "../../esp8266-firmware/src/crypto.rs"]
mod firmware_crypto;

const SEED: [u8; 32] = [0x11; 32];
const EVENT_ID: [u8; 32] = [0xab; 32];
const EXPECTED_PUBKEY: [u8; 32] = [
    0x4f, 0x35, 0x5b, 0xdc, 0xb7, 0xcc, 0x0a, 0xf7, 0x28, 0xef, 0x3c, 0xce, 0xb9, 0x61, 0x5d, 0x90,
    0x68, 0x4b, 0xb5, 0xb2, 0xca, 0x5f, 0x85, 0x9a, 0xb0, 0xf0, 0xb7, 0x04, 0x07, 0x58, 0x71, 0xaa,
];
const EXPECTED_SIG: [u8; 64] = [
    0xba, 0xe2, 0x62, 0xd8, 0xf2, 0xcc, 0x4f, 0x2d, 0x57, 0x69, 0xda, 0xba, 0x78, 0xca, 0xf5, 0x02,
    0x30, 0x22, 0x08, 0x16, 0x07, 0xfb, 0x05, 0x86, 0x02, 0xd3, 0x5d, 0x72, 0x4b, 0xda, 0xb1, 0xa6,
    0xf3, 0x3f, 0xf9, 0x83, 0x3c, 0x7c, 0x03, 0xde, 0x26, 0x8c, 0x6f, 0x7b, 0x2c, 0x0d, 0xa0, 0x4e,
    0x0f, 0x70, 0x63, 0xd6, 0x86, 0x66, 0xe5, 0x12, 0x9f, 0x94, 0xd4, 0xd5, 0xdd, 0x26, 0x1b, 0xf8,
];

#[test]
fn actual_firmware_signer_matches_pre_migration_bip340_vector() {
    assert_eq!(firmware_crypto::pubkey(&SEED), Some(EXPECTED_PUBKEY));
    assert_eq!(firmware_crypto::sign(&SEED, &EVENT_ID), Some(EXPECTED_SIG));
    assert_eq!(firmware_crypto::sign(&SEED, &EVENT_ID), Some(EXPECTED_SIG));
    for invalid in [[0u8; 32], [0xffu8; 32]] {
        assert_eq!(firmware_crypto::pubkey(&invalid), None);
        assert_eq!(firmware_crypto::sign(&invalid, &EVENT_ID), None);
    }
}
